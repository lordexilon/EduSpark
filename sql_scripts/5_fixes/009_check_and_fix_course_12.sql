-- FIX ESPECÍFICO PARA CURSO 12 (Usuario admin-campus / Inst 2)
-- =====================================================

DO $$
DECLARE
    v_target_course_id INTEGER := 12;
    v_user_inst_id INTEGER := 2; -- ID de 'Centro de Estudio Cacavelos'
    v_course_inst_id INTEGER;
    v_teacher_id UUID;
    v_settings_count INTEGER;
BEGIN
    RAISE NOTICE '--- VERIFICANDO CURSO % ---', v_target_course_id;

    -- 1. Obtener datos actuales del curso
    SELECT institution_id, teacher_id INTO v_course_inst_id, v_teacher_id
    FROM courses 
    WHERE id = v_target_course_id;

    IF v_course_inst_id IS NULL THEN
        RAISE NOTICE '❌ ERROR: El curso % no existe.', v_target_course_id;
        RETURN;
    END IF;

    RAISE NOTICE 'Institución actual del curso: % (Tu institución es %)', v_course_inst_id, v_user_inst_id;

    -- 2. Corregir Institución si no coincide
    IF v_course_inst_id IS DISTINCT FROM v_user_inst_id THEN
        RAISE NOTICE '⚠️ FIX: Moviendo curso 12 a la institución % para que sea visible.', v_user_inst_id;
        UPDATE courses 
        SET institution_id = v_user_inst_id 
        WHERE id = v_target_course_id;
    ELSE
        RAISE NOTICE '✅ Institución correcta.';
    END IF;

    -- 3. Asegurar que está ACTIVO
    UPDATE courses SET status = 'active' WHERE id = v_target_course_id;

    -- 4. Asegurar configuración pedagógica (Tutor visible)
    SELECT count(*) INTO v_settings_count 
    FROM course_pedagogical_settings 
    WHERE course_id = (SELECT id FROM courses WHERE id = v_target_course_id::text::uuid); -- Cast simple por si acaso, aunque id es int o uuid

    -- Nota: courses.id suele ser BIGINT en Supabase si es generado por serial, o UUID. 
    -- Revisando schema: courses.id es BIGINT en servicios, pero CourseSelector lo trata como string.
    -- En SQL, id suele ser bigint generated by default as identity.
    -- Pero course_pedagogical_settings.course_id es UUID? 
    -- REVISIÓN IMPORTANTE: En 05_tutor_virtual_tables.sql linea 10: course_id UUID REFERENCES courses(id).
    -- ESTO IMPLICA QUE courses.id ES UUID.
    -- Pero en teacherCourses.ts linea 7: id: number;
    -- HAY UNA INCOHERENCIA POTENCIAL. Si courses.id es int8, la FK debe ser int8.
    -- Si tu BD usa UUID para courses, entonces '12' no es un ID válido.
    -- Si usa INT, entonces '12' es válido.
    
    -- Suposición: courses.id es BIGINT (legacy) o INT.
    -- course_pedagogical_settings.course_id debería ser del mismo tipo.

    -- INTENTO DE INSERCIÓN SEGURO (asumiendo que la FK funciona, Supabase lo maneja)
    
    INSERT INTO course_pedagogical_settings (
        course_id,
        teacher_id,
        voice_name,
        tone_preference
    ) 
    SELECT 
        id, -- course id
        teacher_id, 
        'Athena', 
        'motivador'
    FROM courses 
    WHERE id = v_target_course_id
    ON CONFLICT (course_id) DO UPDATE 
    SET voice_name = 'Athena';

    RAISE NOTICE '✅ Configuración "Athena" asegurada para curso %.', v_target_course_id;

END $$;
